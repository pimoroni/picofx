#!/usr/bin/env python3
"""Assembles a board's manual from its parts and turns it into the HTML the FX drive carries.

The parts every board shares are in boards/manual/ and a board's own in its manual/, numbered
so they interleave. A part in a feature folder goes in only for a board with that feature, as
FEATURES reads it from editor/fx_board.json and manual/manual.json, and so do the lines between
<!-- if feature --> and <!-- end --> in a part, or for a board without it those under
<!-- if not feature -->. A <!-- board name --> line takes that block from the board's
manual/board.md, and manual/manual.json gives the board's own words for each __TERM__.

It writes the assembled text to manual/MANUAL.md, the page to manual/MANUAL.html for opening in
a browser while writing, and the page packed to fx_libs/fx_manual.py, which is what ships.
MANUAL.md and the module are committed and the HTML is not, so the generated page appears once.

The markdown accepted here is a deliberate subset, since this converter has one input and no
reason to grow. It takes ATX headings, paragraphs, "- " lists, pipe tables, links, inline code,
bold, [[Button]] controls and fenced code, whose info string reaches the HTML as a class. A
picker fence is drawn as a picture of the picker instead.

    python3 tools/build_manual.py boards/PIMORONI_MIGHTYFX

The page's header shows picofx's version as the editor pages do, with "preview" after it unless
--release names the release being built.
"""

import argparse
import glob
import html
import json
import os
import re
import sys

from build_editor import embed, shown_version
from manual_mockups import CHIP_BUTTONS, CHIP_ICON, picker_mockup

TEMPLATE_NAME = "manual_template.html"

# The styles for the pictures of the picker, kept beside the module that draws them
MOCKUP_STYLES_NAME = "manual_mockups.css"

# The parts every board's manual shares, from the repository's root
SHARED_PARTS = os.path.join("boards", "manual")

# The colours the manual shares with the picker and the text editor, from the repository's root
SHARED_TOKENS = os.path.join("boards", "editor", "tokens.css")

# The board's description, from its directory
DESCRIPTION = os.path.join("editor", "fx_board.json")

# The board's own settings the description leaves out, whether it has numbered outputs and its
# words for each __TERM__ the parts leave open
MANUAL_SETTINGS = os.path.join("manual", "manual.json")

# The board's blocks, each opened by a <!-- block name --> line and running to the next
BOARD_BLOCKS = os.path.join("manual", "board.md")

# What a board may have, naming the folders of parts and the conditions in them
FEATURES = {
    "outputs": lambda board: board["numbered_outputs"],
    "strips": lambda board: bool(board["strips"]),
    "screens": lambda board: bool(board["screens"]),
    "two_screens": lambda board: bool(board["screens"]) and len(board["screens"]["ports"]) > 1,
    "hub": lambda board: bool(board["screens"] and board["screens"]["hub"]),
    "sound": lambda board: bool(board["sound"]),
    "sensor": lambda board: bool(board.get("sensor")),
    "examples": lambda board: bool(board["examples"]),
    "discover": lambda board: bool(board.get("examples_index")),
}

# A control on the picker's page, written [[Save to board]] and drawn as the picker's button
BUTTON = re.compile(r"\[\[([^\]]+)\]\]")

# A label in the contents list over the sections after it, written <!-- contents The label -->
GROUP = re.compile(r"^<!-- contents (.+) -->$")

CONDITION = re.compile(r"<!-- if (not )?(\w+) -->")
CONDITION_END = "<!-- end -->"
BLOCK = re.compile(r"^<!-- block (\w+) -->$", re.MULTILINE)
PULL = re.compile(r"<!-- board (\w+) -->")

MARKDOWN_HEADER = ("<!-- Generated from boards/manual/ and this board's own parts by "
                   "tools/build_manual.py. Edit those and rebuild, since edits here are lost. -->\n\n")

# The generated module holds the page packed as the editor's pages are, and fx_drive inflates
# it onto the drive.
MODULE_HEADER = """# SPDX-FileCopyrightText: 2026 Christopher Parrott for Pimoroni Ltd
#
# SPDX-License-Identifier: MIT

# Generated by tools/build_manual.py from the manual's parts. Edit those, not this file.

"""


def slug(text):
    """Make the anchor a heading gets, which is also what a link in the source points at."""
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", text.lower())).strip("-")


def button(match):
    """Draw a [[name]] control as the picker draws it, with the chip where the picker has one."""
    name = match.group(1)
    return '<span class="button">{}{}</span>'.format(
        CHIP_ICON if name in CHIP_BUTTONS else "", name)


def inline(text):
    """Mark up inline text, escaping it first so the source cannot inject markup of its own."""
    escaped = html.escape(text, quote=False)
    escaped = re.sub(r"`([^`]+)`", r"<code>\1</code>", escaped)
    escaped = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", escaped)
    escaped = BUTTON.sub(button, escaped)
    return re.sub(r"\[([^\]]+)\]\(([^)]+)\)", link_markup, escaped)


def link_markup(found):
    """Mark up a link, so one to another site opens in a new tab like the picker's."""
    text, target = found.group(1), found.group(2)
    if re.match(r"https?://", target):
        return '<a href="{}" target="_blank" rel="noopener">{}</a>'.format(target, text)
    return '<a href="{}">{}</a>'.format(target, text)


def mark(role, text):
    return '<span class="{}">{}</span>'.format(role, text) if text else text


def setting(token):
    """Mark up a name=value pair, or a bare word where it has no value."""
    trailing = ""
    while token.endswith(","):
        token, trailing = token[:-1], token[-1:] + trailing
    name, divider, value = token.partition("=")
    if not divider:
        return mark("s-name", name) + trailing
    return mark("s-name", name) + mark("s-punc", "=") + mark("s-value", value) + trailing


def placeholders(text, roles):
    """Mark each <placeholder> by the position it stands in, spaces and all."""
    standing = [0]

    def taken(match):
        role = roles[min(standing[0], len(roles) - 1)]
        standing[0] += 1
        return mark(role, match.group(0))

    return re.sub(r"&lt;[^&]*&gt;", taken, text)


def highlight(line, shape=False):
    """
    Mark up an entry by the role each word plays, over already-escaped text.

    Colour shows the same three roles as the shape in Writing an entry, so an example reads as an
    instance of it. A shape is positional, since its placeholders stand where a selector, an
    effect and their settings go.
    """
    if line.lstrip().startswith("["):
        return mark("s-scene", line)

    before, divider, after = line.partition(":")
    if not divider:
        return line

    if shape:
        return (placeholders(before, ("s-target", "s-name"))
                + mark("s-colon", ":")
                + placeholders(after, ("s-effect", "s-name")))

    left = "".join(word if not word.strip()
                   else setting(word) if "=" in word
                   else mark("s-target", word)
                   for word in re.split(r"(\s+)", before))

    # The first word names the effect unless it holds an "=". A board, remote or motion entry has
    # only settings, and a bare word after a setting is part of its value, as Night is in starts=scene Night
    right = []
    named = False
    valued = False
    for word in re.split(r"(\s+)", after):
        if not word.strip():
            right.append(word)
        elif named or "=" in word:
            right.append(setting(word))
            valued = valued or "=" in word
        elif valued:
            right.append(mark("s-value", word))
        else:
            right.append(mark("s-effect", word))
            named = True

    return left + mark("s-colon", ":") + "".join(right)


def cells(row):
    """Split a table row on unescaped pipes, keeping an escaped pipe as text."""
    parts = re.split(r"(?<!\\)\|", row.strip().strip("|"))
    return [part.replace("\\|", "|").strip() for part in parts]


def blocks(lines):
    """Split the source into (kind, payload) pairs, where kind says what to render it as."""
    found = []
    index = 0
    while index < len(lines):
        line = lines[index]

        if not line.strip():
            index += 1
        elif GROUP.match(line):
            found.append(("group", GROUP.match(line).group(1)))
            index += 1
        elif line.startswith("```"):
            language = line[3:].strip()
            index += 1
            body = []
            while index < len(lines) and not lines[index].startswith("```"):
                body.append(lines[index])
                index += 1
            index += 1
            found.append(("code", (language, body)))
        elif line.startswith("#"):
            level = len(line) - len(line.lstrip("#"))
            found.append(("heading", (level, line[level:].strip())))
            index += 1
        elif line.lstrip().startswith("|"):
            rows = []
            while index < len(lines) and lines[index].lstrip().startswith("|"):
                rows.append(lines[index])
                index += 1
            found.append(("table", rows))
        elif line.startswith("- "):
            items = []
            while index < len(lines) and lines[index].startswith("- "):
                items.append(lines[index][2:].strip())
                index += 1
            found.append(("list", items))
        else:
            body = []
            while index < len(lines) and lines[index].strip() and not (
                    lines[index].startswith(("#", "```", "|", "- "))):
                body.append(lines[index].strip())
                index += 1
            found.append(("paragraph", " ".join(body)))

    return found


def render(found):
    """Render the page body, and collect the headings a contents list is built from."""
    out = []
    contents = []

    for kind, payload in found:
        # Check if this is a group, which only labels the contents list
        if kind == "group":
            contents.append((0, None, payload))
            continue
        if kind == "heading":
            level, text = payload
            # Check if this is the title, which goes in the page's header and not the body
            if level == 1:
                continue
            anchor = slug(text)
            # Check if an earlier heading has this anchor, since a link could never reach the second
            if any(anchor == taken for _, taken, _ in contents):
                sys.exit("two headings are both {!r}".format(text))
            contents.append((level, anchor, text))
            out.append('<h{0} id="{1}">{2}</h{0}>'.format(level, anchor, inline(text)))

        elif kind == "paragraph":
            out.append("<p>{}</p>".format(inline(payload)))

        elif kind == "list":
            out.append("<ul>{}</ul>".format(
                "".join("<li>{}</li>".format(inline(item)) for item in payload)))

        elif kind == "code":
            language, body = payload
            if language == "picker":
                out.append(picker_mockup(body))
                continue
            escaped = [html.escape(line, quote=False) for line in body]
            if language in ("entry", "shape"):
                escaped = [highlight(line, language == "shape") for line in escaped]
            out.append('<pre class="{}"><code>{}</code></pre>'.format(
                language, "\n".join(escaped)))

        elif kind == "table":
            # Row two is the header separator, which carries nothing to render.
            header, _, *rest = payload
            out.append('<div class="scroll"><table>')
            out.append("<thead><tr>{}</tr></thead>".format(
                "".join("<th>{}</th>".format(inline(c)) for c in cells(header))))
            out.append("<tbody>")
            for row in rest:
                out.append("<tr>{}</tr>".format(
                    "".join("<td>{}</td>".format(inline(c)) for c in cells(row))))
            out.append("</tbody></table></div>")

    return "\n".join(out), contents


def contents_entry(anchor, text, under, opened):
    """Draw one section in the contents list, as a details holding its subsections where it has any."""
    link = '<a href="#{}">{}</a>'.format(anchor, inline(text))
    if not under:
        return "<li>{}</li>".format(link)
    return "<li><details{}><summary>{}</summary><ul>{}</ul></details></li>".format(
        " open" if opened else "", link, "".join(under))


def table_of_contents(contents):
    """
    Build the contents list, with the sections in their groups.

    A section with subsections becomes a details, which opens and closes with no
    script. Its summary holds the section's link, and the template's one script opens
    the entry when that link is followed. The sections before the first group start open.

    A group named "fold" has no label. Its first section holds the group's other
    sections, shut, each with its own subsections a level further in.
    """
    sections = []
    for level, anchor, text in contents:
        if level in (0, 2) or not sections:
            sections.append((level, anchor, text, []))
        else:
            sections[-1][3].append('<li><a href="#{}">{}</a></li>'.format(anchor, inline(text)))

    items = ['<nav class="contents"><h2>Contents</h2><ul>']
    groups = 0
    folding = None
    for level, anchor, text, under in sections:
        if level == 0:
            if folding:
                items.append(contents_entry(*folding, opened=False))
            folding = None
            groups += 1
            if text == "fold":
                folding = []
            else:
                items.append('<li class="group">{}</li>'.format(inline(text)))
            continue
        if folding == []:
            folding = [anchor, text, under]
        elif folding:
            folding[2] = folding[2] + [contents_entry(anchor, text, under, opened=False)]
        else:
            items.append(contents_entry(anchor, text, under, opened=groups == 0))
    if folding:
        items.append(contents_entry(*folding, opened=False))
    items.append("</ul></nav>")
    return "\n".join(items)


def board_parts(part_folders, board):
    """
    List the board's numbered parts in number order, from the shared parts and its own, and from
    a feature folder only where the board has that feature. A part of the board's own adds to the
    shared ones and cannot replace one.
    """
    folders = []
    for folder in part_folders:
        folders.append(folder)
        for name in sorted(os.listdir(folder)):
            if not os.path.isdir(os.path.join(folder, name)):
                continue
            if name not in FEATURES:
                sys.exit("{} is not a feature folder the build knows".format(
                    os.path.join(folder, name)))
            if FEATURES[name](board):
                folders.append(os.path.join(folder, name))
    parts = [part for where in folders for part in glob.glob(os.path.join(where, "[0-9][0-9]_*.md"))]
    names = [os.path.basename(part) for part in parts]
    twice = sorted({name for name in names if names.count(name) > 1})
    if twice:
        sys.exit("{} is both a shared part and the board's own".format(", ".join(twice)))
    return sorted(parts, key=os.path.basename)


def board_blocks(board_dir):
    """Read the board's blocks by name from its board.md, or none where it has no board.md."""
    path = os.path.join(board_dir, BOARD_BLOCKS)
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as f:
        pieces = BLOCK.split(f.read())
    if pieces[0].strip():
        sys.exit("{} has text before its first block".format(path))
    names = pieces[1::2]
    twice = sorted({name for name in names if names.count(name) > 1})
    if twice:
        sys.exit("{} has more than one {} block".format(path, ", ".join(twice)))
    return {name: body.strip("\n") for name, body in zip(names, pieces[2::2])}


def expand(path, text, board, own_blocks, pulled):
    """
    Settle a part's conditions and fill its board lines from the board's blocks, adding the
    name of each block it takes to the pulled set.

    A condition that does not hold and opens after a blank line goes with the blank line after
    it, so the blank lines either side do not double up. One inside a paragraph or a table
    keeps it.
    """
    out = []
    feature = None
    keeping = True
    drop_blank = False
    for line in text.split("\n"):
        if drop_blank:
            drop_blank = False
            if not line.strip():
                continue
        opened = CONDITION.fullmatch(line)
        pull = PULL.fullmatch(line)
        if opened:
            if feature:
                sys.exit("{} opens a condition inside another".format(path))
            feature = opened.group(2)
            if feature not in FEATURES:
                sys.exit("{} tests {}, which is not a feature the build knows".format(
                    path, feature))
            keeping = FEATURES[feature](board) != bool(opened.group(1))
        elif line == CONDITION_END:
            if not feature:
                sys.exit("{} ends a condition it never opened".format(path))
            drop_blank = not keeping and (not out or not out[-1].strip())
            feature = None
            keeping = True
        elif not keeping:
            continue
        elif pull:
            if pull.group(1) not in own_blocks:
                sys.exit("{} takes the board's {} block, which its {} does not have".format(
                    path, pull.group(1), BOARD_BLOCKS))
            pulled.add(pull.group(1))
            out.append(own_blocks[pull.group(1)])
        else:
            out.append(line)
    if feature:
        sys.exit("{} leaves its {} condition open".format(path, feature))
    return "\n".join(out)


def assemble(board_dir, repo_dir):
    """Assemble the board's manual as markdown, with its parts one blank line apart and its terms filled in."""
    with open(os.path.join(board_dir, DESCRIPTION), encoding="utf-8") as f:
        board = json.load(f)
    with open(os.path.join(board_dir, MANUAL_SETTINGS), encoding="utf-8") as f:
        manual = json.load(f)

    texts = []
    folders = [os.path.join(repo_dir, SHARED_PARTS), os.path.join(board_dir, "manual")]
    has = dict(board, numbered_outputs=manual["numbered_outputs"])
    own_blocks = board_blocks(board_dir)
    pulled = set()
    for part in board_parts(folders, has):
        with open(part, encoding="utf-8") as f:
            texts.append(expand(part, f.read(), has, own_blocks, pulled).strip("\n"))
    text = "\n\n".join(texts) + "\n"

    unused = sorted(set(own_blocks) - pulled)
    if unused:
        sys.exit("{} has {}, which no part the board takes uses".format(
            BOARD_BLOCKS, ", ".join(unused)))

    for term, words in manual["terms"].items():
        placeholder = "__{}__".format(term)
        if placeholder not in text:
            sys.exit("{} gives {}, which no part the board takes uses".format(
                MANUAL_SETTINGS, term))
        text = text.replace(placeholder, words)
    left = sorted(set(re.findall(r"__[A-Z_]+__", text)))
    if left:
        sys.exit("the manual has {} unfilled".format(", ".join(left)))
    return text


def build(markdown, tools_dir, version):
    found = blocks(markdown.split("\n"))
    body, contents = render(found)

    title = next(text for kind, (level, text) in
                 ((k, p) for k, p in found if k == "heading") if level == 1)

    with open(os.path.join(tools_dir, TEMPLATE_NAME), encoding="utf-8") as f:
        template = f.read()

    page = template.replace("{{TITLE}}", html.escape(title, quote=False))
    page = page.replace("{{VERSION}}", html.escape(version, quote=False))
    page = page.replace("{{CONTENTS}}", table_of_contents(contents))
    page = page.replace("{{BODY}}", body)
    with open(os.path.join(tools_dir, MOCKUP_STYLES_NAME), encoding="utf-8") as f:
        page = page.replace("{{MOCKUP_STYLES}}", f.read().strip())
    with open(os.path.join(tools_dir, "..", SHARED_TOKENS), encoding="utf-8") as f:
        page = page.replace("{{TOKENS}}", f.read().strip())

    # Check if any character takes more than one byte. fx_drive compares and writes the page a piece
    # at a time, counting characters against a file that counts bytes
    if not page.isascii():
        stray = sorted({c for c in page if not c.isascii()})
        sys.exit("the page contains {}, and it has to be ASCII to reach the drive "
                 "a piece at a time".format(", ".join(repr(c) for c in stray)))

    return page


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--release", metavar="VERSION",
                        help="the release being built, which must be picofx's version")
    parser.add_argument("board_dir", help="a board directory holding manual/manual.json")
    args = parser.parse_args()

    tools_dir = os.path.dirname(os.path.abspath(__file__))
    markdown = assemble(args.board_dir, os.path.dirname(tools_dir))
    page = build(markdown, tools_dir, shown_version(os.path.dirname(tools_dir), args.release))

    source = os.path.join(args.board_dir, "manual", "MANUAL.md")
    with open(source, "w", encoding="utf-8", newline="\n") as f:
        f.write(MARKDOWN_HEADER)
        f.write(markdown)

    preview = os.path.join(args.board_dir, "manual", "MANUAL.html")
    with open(preview, "w", encoding="utf-8", newline="\n") as f:
        f.write(page)

    module = os.path.join(args.board_dir, "fx_libs", "fx_manual.py")
    with open(module, "w", encoding="utf-8", newline="\n") as f:
        f.write(MODULE_HEADER)
        f.write(embed("MANUAL", page))

    print("{} bytes of page: {}, {} and {}".format(len(page), source, preview, module))


if __name__ == "__main__":
    main()
